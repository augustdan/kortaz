export function buildTenantRolesAndPermissions(tenantId: string): {
  roles: Role[];
  permissions: Permission[];
} {
  const roleNames: Record<RoleCode, { name: string; desc: string }> = {
    SUPER_ADMIN: { name: 'Super Admin', desc: 'Administração global da plataforma SaaS' },
    OWNER: { name: 'Proprietário', desc: 'Controle total da barbearia e unidades' },
    MANAGER: { name: 'Gerente', desc: 'Gestão operacional, agenda e equipe' },
    BARBER: { name: 'Barbeiro', desc: 'Agenda própria, comissões e registro de atendimentos' },
    RECEPTIONIST: { name: 'Recepcionista', desc: 'Atendimento, confirmações e caixa' },
    CUSTOMER: { name: 'Cliente', desc: 'Agendamento e histórico pessoal' },
  };

  const roles: Role[] = [];
  const permissions: Permission[] = [];
  const codes: RoleCode[] = ['OWNER', 'MANAGER', 'BARBER', 'RECEPTIONIST', 'CUSTOMER'];
  const resources = Object.keys(DEFAULT_ROLE_MATRIX.OWNER) as AppResource[];

  for (const code of codes) {
    const roleId = `role-${tenantId}-${code.toLowerCase()}`;
    roles.push({
      id: roleId,
      tenant_id: tenantId,
      code,
      name: roleNames[code].name,
      description: roleNames[code].desc,
    });

    for (const resource of resources) {
      if (resource === 'super_admin') continue;
      const def = DEFAULT_ROLE_MATRIX[code][resource];
      permissions.push({
        id: `perm-${roleId}-${resource}`,
        role_id: roleId,
        tenant_id: tenantId,
        resource,
        can_view: def.view,
        can_create: def.create,
        can_edit: def.edit,
        can_delete: def.delete,
      });
    }
  }

  return { roles, permissions };
}

