function offsetDayIso(dayOffset: number, hhmm: string): string {
  const now = new Date();
  const base = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + dayOffset));
  const y = base.getUTCFullYear();
  const m = String(base.getUTCMonth() + 1).padStart(2, '0');
  const d = String(base.getUTCDate()).padStart(2, '0');
  return new Date(`${y}-${m}-${d}T${hhmm}:00-03:00`).toISOString();
}

function offsetDayDate(dayOffset: number): string {
  const now = new Date();
  const base = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + dayOffset));
  return base.toISOString().slice(0, 10);
}

